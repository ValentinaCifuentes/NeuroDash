"""
Pydantic schemas for the NeuraDash Telemetry Plugin (SENSE/CONNECT layer).

Separated from the CORE schemas (backend/app/schemas.py) to enforce
modular plugin boundaries. The CORE system must function without these
schemas being imported.

All sensor observations carry mandatory DataProvenance metadata to ensure
full traceability and synthetic-data transparency.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from typing import Literal

from pydantic import BaseModel, Field, field_validator, model_validator


class SignalType(StrEnum):
    """Supported telemetry signal types for the SENSE layer."""

    ENVIRONMENTAL_NOISE = "environmental_noise"
    MOVEMENT_AGITATION = "movement_agitation"
    AMBIENT_LIGHT = "ambient_light"
    HEART_RATE = "heart_rate"


# Canonical unit for each signal — used for validation.
SIGNAL_UNIT_MAP: dict[SignalType, str] = {
    SignalType.ENVIRONMENTAL_NOISE: "dBA",
    SignalType.MOVEMENT_AGITATION: "g",
    SignalType.AMBIENT_LIGHT: "lux",
    SignalType.HEART_RATE: "bpm",
}


class DataProvenance(BaseModel):
    """
    Mandatory provenance metadata attached to every sensor observation.

    Privacy-by-design: we record *where* the data came from and whether it
    is synthetic so that downstream consumers can audit lineage without
    ambiguity.
    """

    origin: str = Field(
        ...,
        min_length=1,
        description="Source identifier (e.g. 'smartwatch_xyz', 'neuradash_simulator_v1').",
    )
    synthetic_flag: bool = Field(
        ...,
        description="True when the observation was generated by a simulator.",
    )


class SensorObservation(BaseModel):
    """
    A single sensor reading within a telemetry payload.

    The ``unit`` field is validated against the canonical unit for the
    declared ``signal`` type (e.g. ``environmental_noise`` must use ``dBA``).
    This enforces the privacy rule: we never store raw audio, only decibels.
    """

    signal: SignalType = Field(..., description="Type of sensor signal.")
    value: float = Field(..., description="Numeric reading from the sensor.")
    unit: str = Field(..., description="Measurement unit (must match signal type).")
    window: str = Field(
        ...,
        description="Temporal window label for this reading (e.g. '15m', 'adaptive').",
    )
    provenance: DataProvenance = Field(
        ...,
        description="Mandatory origin and synthetic-flag metadata.",
    )

    @model_validator(mode="after")
    def validate_unit_matches_signal(self) -> "SensorObservation":
        """Ensure the declared unit matches the canonical unit for this signal type."""
        expected_unit = SIGNAL_UNIT_MAP.get(self.signal)
        if expected_unit is not None and self.unit != expected_unit:
            raise ValueError(
                f"Signal '{self.signal.value}' requires unit '{expected_unit}', "
                f"got '{self.unit}'."
            )
        return self


class TelemetryPayload(BaseModel):
    """
    Root payload for ingesting telemetry data from an external device or
    simulator into NeuraDash.
    """

    subject_id: str = Field(..., min_length=1, description="Patient/subject identifier.")
    device_id: str = Field(..., min_length=1, description="Source device identifier.")
    timestamp: datetime = Field(
        ...,
        description="Payload-level timestamp (ISO-8601 UTC-aware).",
    )
    observations: list[SensorObservation] = Field(
        ...,
        min_length=1,
        description="One or more sensor observations in this payload.",
    )

    @field_validator("timestamp")
    @classmethod
    def timestamp_must_be_aware(cls, v: datetime) -> datetime:
        """Reject naive (timezone-unaware) timestamps to prevent temporal bugs."""
        if v.tzinfo is None:
            raise ValueError("timestamp must be timezone-aware (include UTC offset).")
        return v


# ---------------------------------------------------------------------------
# Simulation endpoint schemas
# ---------------------------------------------------------------------------

SimulationProfile = Literal["estable", "riesgo_acumulado", "datos_insuficientes"]


class SimulationRequest(BaseModel):
    """Request body for the ``POST /api/v1/telemetry/simulate`` endpoint."""

    subject_id: str = Field(..., min_length=1, description="Target subject to simulate data for.")
    profile: SimulationProfile = Field(
        ...,
        description=(
            "Simulation profile: 'estable' (low-risk baseline), "
            "'riesgo_acumulado' (escalating risk), or "
            "'datos_insuficientes' (stale/missing data)."
        ),
    )
    seed: int | None = Field(
        default=None,
        description="Optional RNG seed for reproducible simulations.",
    )


class TelemetryResponse(BaseModel):
    """Standard response for telemetry ingestion and simulation endpoints."""

    status: str = Field(..., description="Operation status ('ok' or 'error').")
    stored_count: int = Field(..., ge=0, description="Number of observations persisted.")
    subject_id: str = Field(..., description="Subject the data was stored for.")
    message: str | None = Field(default=None, description="Optional human-readable detail.")
